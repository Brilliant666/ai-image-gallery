/* Character assembly invariants: run the same model that is embedded in the gallery. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname,'../sites/character/scripts/gallery.js'),'utf8');
const Model = vm.runInNewContext(source.split('(function(){')[0]+'; CharacterModel;');
let result=Model.compose([{tags:'long hair, blue eyes'},{tags:'BLUE EYES, full_body'}],'1girl, solo','full body, smile');
assert.equal(result.text,'1girl, solo, long hair, blue eyes, full_body, smile');
assert.equal(result.conflict,false);
result=Model.compose([{tags:'2girls, reading, sitting'},{tags:'white shirt'}],'1girl, solo','solo, smile');
assert.equal(result.text,'2girls, reading, sitting, white shirt, smile');assert.equal(result.conflict,true);
result=Model.compose([{tags:'2boys, standing'}],'1boy, solo','');
assert.equal(result.text,'2boys, standing');assert.equal(result.conflict,true);
const style={id:'H001',set:'hair',cat:'髪型'}, outfit={id:'O001',set:'outfit',cat:'制服・学生'};
const map=new Map([[style.id,style],[outfit.id,outfit]]);
let state=Model.restore({selected:{style:'H001',outfit:'O001',pose:'https://example.com/attack'},extras:'smile',subject:'<script>'},map,['style','outfit','pose']);
assert.equal(JSON.stringify(state.selected),JSON.stringify({style:'H001',outfit:'O001'}));assert.equal(state.subject,'1girl, solo');
assert.equal(Object.keys(Model.restore({selected:{style:'O001'}},map,['style']).selected).length,0);
assert.equal(Model.restore({extras:'x'.repeat(2500)},map,[]).extras.length,2000);
assert.equal(Model.slot({set:'hair',cat:'瞳の形'}),'eyeShape');assert.equal(Model.slot({set:'hair',cat:'目の色'}),'eyeColor');
console.log('Character model: deduplication, multi-person conflict and stored selection validation passed');
